function enrichTemplate(
  raw: (typeof RAW_TEMPLATES)[number]
): CaptionTemplateSpec {
  const isPopular = POPULAR_TEMPLATE_IDS.includes(raw.id);
  const previewPosterUrl = `https://captik.in/previews/p/${raw.id}.webp`;
  const previewVideoUrl = `https://captik.in/previews/t/${raw.id}.mp4`;

  // 1. Check classic templates first
  const classic = CLASSIC_TEMPLATE_CONFIGS[raw.id];
  if (classic) {
    return {
      ...raw,
      popular: isPopular,
      ...classic,
      previewPosterUrl,
      previewVideoUrl,
    };
  }

  // 2. Check authentic LOOK_SPECS from captik.in production bundle
  const look = CAPTIK_LOOK_SPEC_MAP[raw.id];
  if (look) {
    const textColor =
      look.color ??
      look.spatialTheme?.caption.color ??
      look.reelTheme?.supportColor ??
      '#FFFFFF';
    const emphasisColor =
      look.impact?.litColor ??
      look.impact?.color ??
      look.accent ??
      look.spatialTheme?.caption.accent ??
      look.reelTheme?.gradient?.[1] ??
      look.chip?.bg ??
      '#FFE500';
    const boxBg =
      look.chip?.bg ??
      look.impact?.chip?.bg ??
      look.spatialTheme?.caption.chip?.bg ??
      look.reelTheme?.banner?.bg;
    const shadowStyle = look.shadow
      ? `0 ${look.shadow.offsetY ?? 4}px ${look.shadow.blurPx}px ${look.shadow.color}`
      : look.glow
      ? `0 0 ${look.glow.px}px ${look.glow.color ?? emphasisColor}`
      : '0 4px 16px rgba(0,0,0,0.65)';

    let animationType: CaptionTemplateSpec['animationType'] = 'word-glow';
    let badge: CaptionTemplateSpec['badge'] = isPopular ? 'Popular' : undefined;
    let description = `${look.name} (${look.family}) — ${look.font.split(',')[0].replace(/"/g, '')} ${look.sizePx}px`;

    if (look.family === 'story') {
      animationType = 'property-tag';
      badge = 'Property';
      description = `Property reel architectural callout (${look.reel ?? look.story}) with ${look.reelTheme ? '3-stop gradient & outline figure' : 'agent price lockup'}.`;
    } else if (look.family === 'spatial') {
      animationType = 'spatial-float';
      badge = '3D Around';
      description = `Spatial "${look.spatialTheme?.layout ?? look.spatial}" layout (${look.spatialTheme?.texture ?? '3D'} texture, ${look.spatialTheme?.motion ?? 'spring'} motion) around your head.`;
    } else if (look.behindSubject || raw.behind) {
      animationType = 'behind-hero';
      badge = isPopular ? 'Popular' : 'Behind you';
      if (look.impact) {
        description = `Behind-subject ${look.impact.font.split(',')[0].replace(/"/g, '')} ${look.impact.sizePx}px hero lockup + ${look.font.split(',')[0].replace(/"/g, '')} foreground captions.`;
      } else if (look.wholeBehind) {
        description = `Full phrase rendered behind your head in ${look.font.split(',')[0].replace(/"/g, '')} ${look.sizePx}px.`;
      } else if (look.stack) {
        description = `Multi-row stacked typography (${look.stack.rowScale.join('x / ')}x) with depth layering.`;
      }
    } else if (look.chip) {
      animationType = 'karaoke-pill';
    }

    return {
      ...raw,
      popular: isPopular,
      fontFamily: look.font,
      fontWeight: look.weight,
      uppercase: look.transform === 'uppercase' || !!look.impact?.uppercase,
      textColor,
      emphasisColor,
      secondaryColor: look.gradient?.to ?? '#E4E4E7',
      boxBg,
      glowColor: look.glow?.color,
      strokeColor: look.stroke?.color,
      strokeWidth: look.stroke?.px,
      shadowStyle,
      animationType,
      badge,
      description,
      lookSpec: look,
      previewPosterUrl,
      previewVideoUrl,
    };
  }

  return {
    ...raw,
    popular: isPopular,
    fontFamily: 'Montserrat, sans-serif',
    fontWeight: 800,
    uppercase: true,
    textColor: '#FFFFFF',
    emphasisColor: '#F59E0B',
    secondaryColor: '#E2E8F0',
    shadowStyle: '0 4px 16px rgba(0,0,0,0.85)',
    animationType: 'word-glow',
    previewPosterUrl,
    previewVideoUrl,
    description: 'Word-synced dynamic creator caption preset.',
  };
}

